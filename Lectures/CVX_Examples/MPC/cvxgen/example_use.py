"""Example code to use MPC (cvxpy)
Python version of ExampleUse.m (and of cvxsolve.m, its CVX check).

Solves the MPC problem defined in description.cvxgen (5 states, 2 inputs,
horizon T = 10):

    minimize   sum_{t=0..T} (x_t'Q x_t + u_t'R u_t) + x_{T+1}'Q_final x_{T+1}
    subject to x_{t+1} = A x_t + B u_t       (dynamics)
               |u_t| <= u_max                (actuator limit, each input)
               ||u_{t+1} - u_t||_inf <= S    (slew-rate limit)

In MATLAB this uses a C solver generated by CVXGEN. In Python the problem is
written directly in cvxpy with Parameters (A, B, x_0, u_max, S): cvxpy
compiles it once, and later solves with new parameter values skip that step.
That is the cvxpy counterpart of a generated solver. (For embedded C code
from a cvxpy problem, see CVXPYgen: https://github.com/cvxgrp/cvxpygen.)

This is a single open-loop solve on a random system, to show the interface
and speed. A real MPC controller would re-solve every time step from the
measured state and apply only u_0 (receding horizon).

Requires: numpy, matplotlib, cvxpy (see ../../requirements.txt).
Output:   predicted states printed, and a figure of the inputs with the limits.
"""

import time as timer

import cvxpy as cp
import matplotlib.pyplot as plt
import numpy as np

# Dimensions (must match description.cvxgen)
n, m, T = 5, 2, 10          # states, inputs, horizon


def build_mpc(Q, Q_final, R):
    """Build the MPC problem once; returns (problem, parameters, variables)."""
    A = cp.Parameter((n, n), name="A")              # dynamics matrix
    B = cp.Parameter((n, m), name="B")              # input matrix
    x_0 = cp.Parameter(n, name="x_0")               # initial state
    u_max = cp.Parameter(nonneg=True, name="u_max") # amplitude limit
    S = cp.Parameter(nonneg=True, name="S")         # slew-rate limit

    x = cp.Variable((n, T + 2))     # x[:, t] = x_t, t = 0..T+1 (column 0 is x_0)
    u = cp.Variable((m, T + 1))     # u[:, t] = u_t, t = 0..T

    cost = sum(cp.quad_form(x[:, t], Q) + cp.quad_form(u[:, t], R) for t in range(T + 1))
    cost += cp.quad_form(x[:, T + 1], Q_final)
    constraints = [
        x[:, 0] == x_0,
        x[:, 1:] == A @ x[:, :-1] + B @ u,          # dynamics constraints
        cp.abs(u) <= u_max,                         # maximum input box constraint
        cp.abs(cp.diff(u, axis=1)) <= S,            # slew rate (inf-norm = elementwise)
    ]
    problem = cp.Problem(cp.Minimize(cost), constraints)
    params = dict(A=A, B=B, x_0=x_0, u_max=u_max, S=S)
    return problem, params, (x, u)


def main():
    rng = np.random.default_rng(0)

    # Problem data. Q, R, Q_final are fixed (PSD) cost weights.
    problem, params, (x, u) = build_mpc(Q=np.eye(n), Q_final=np.eye(n), R=np.eye(m))
    params["A"].value = rng.standard_normal((n, n))
    params["B"].value = rng.standard_normal((n, m))
    params["S"].value = 10
    params["u_max"].value = 2
    params["x_0"].value = np.ones(n)

    # First solve: cvxpy compiles the problem, then calls the solver.
    # Clarabel is an interior-point solver, like CVXGEN's. OSQP (first-order)
    # often stops at "inaccurate" on these random, unstable systems.
    tic = timer.perf_counter()
    problem.solve(solver=cp.CLARABEL)
    print(f"First solve (compile + solve): {timer.perf_counter() - tic:.4f} s")

    # Check convergence, and display the optimal variable value.
    if problem.status != cp.OPTIMAL:
        raise RuntimeError(f"failed to converge: {problem.status}")
    np.set_printoptions(precision=3, suppress=True)
    print("Predicted states x_1..x_{T+1} (one column per time step):")
    print(x.value[:, 1:])

    # Re-solve from a new initial state: only the parameter value changes, so
    # cvxpy reuses the compiled problem (the CVXGEN idea).
    params["x_0"].value = -np.ones(n)
    tic = timer.perf_counter()
    problem.solve(solver=cp.CLARABEL)
    print(f"Second solve (new x_0, parameters only): {timer.perf_counter() - tic:.4f} s")

    # Plot the planned inputs against the actuator limits
    plt.figure()
    plt.title("MPC planned inputs (second solve)")
    plt.step(range(T + 1), u.value.T, where="post", label=["u_1", "u_2"])
    for s in (1, -1):
        plt.axhline(s * params["u_max"].value, color="r", linestyle="--")
    plt.xlabel("Time step t")
    plt.ylabel("Input u_t")
    plt.grid(True)
    plt.legend()
    plt.show()


if __name__ == "__main__":
    main()
